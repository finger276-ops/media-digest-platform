-- Журнал применённых миграций. Выполнить первым, один раз.
--
-- До этой таблицы схема применялась вручную — отдельными файлами в sql/*.sql,
-- в порядке "как получится". Узнать, что уже применено на конкретной базе,
-- можно было только вручную открыв SQL Editor и посмотрев список таблиц —
-- отсюда platform_sessions_schema.sql, про который до этой миграции нельзя
-- было сказать точно, накатан ли он на проде.
--
-- Дальше — по одному пронумерованному файлу на изменение схемы. Каждый файл
-- идемпотентен (create table/index if not exists) и сам себя регистрирует
-- последней строкой — insert в эту таблицу. Поэтому файл безопасно вставить
-- и выполнить в SQL Editor повторно, даже если неизвестно, применялся ли он
-- раньше: DDL просто ничего не сделает, а запись в журнале не задвоится
-- (primary key на version).

create table if not exists public.schema_migrations (
    version text primary key,
    name text not null,
    applied_at timestamptz not null default now()
);

comment on table public.schema_migrations is
    'Журнал применённых миграций схемы — какие файлы из sql/migrations уже накатаны';
