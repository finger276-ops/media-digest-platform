# -*- coding: utf-8 -*-
"""Общие настройки визуализации Altair — один источник правды для цветов и осей.

Причины для этого модуля — два независимых замечания с живой платформы:

1. Подписи периодов на оси X накладывались друг на друга («24.04.2026–
   30.04.2026» и соседняя дата слипались в узких панелях facet-графика).
   Правится не индивидуально в каждом графике, а один раз — общей настройкой
   оси с наклоном подписей (при наклоне тот же текст занимает меньше
   горизонтального места, чем при angle=0).
2. Цвета серий назначались Vega по умолчанию (categorical scheme), поэтому
   одна и та же метрика («BPI», «Сообщения») могла получить разный цвет в
   разных графиках, а иногда — на разных фасетах одного графика. Здесь —
   фиксированная, проверенная на различимость палитра с фиксированным
   порядком: цвет закреплён за именем метрики, а не за порядком её выбора.

Ничего из этого не добавляет вычислений: и наклон подписей, и фиксированная
шкала цвета — статические поля той же Vega-Lite спецификации, которая и так
уходит в браузер. Плавные линии (interpolate="monotone") — тоже штатная
опция Vega-Lite, не меняющая объём данных и число точек.
"""

from __future__ import annotations

import altair as alt

# Категориальная палитра, различимая для людей с разными типами цветового
# зрения (проверено попарно для первых слотов) — фиксированный порядок,
# цвет назначается по имени категории, а не по порядку появления в данных.
CATEGORICAL_PALETTE = [
    "#2a78d6",  # синий
    "#eb6834",  # оранжевый
    "#1baf7a",  # бирюзовый
    "#eda100",  # жёлтый
    "#e87ba4",  # розовый
    "#008300",  # зелёный
    "#4a3aa7",  # фиолетовый
    "#e34948",  # красный
]

# Тональность — единственная категориальная шкала с фиксированной семантикой
# (зелёный/серый/красный), а не назначаемая по кругу палитра. Раньше жила
# только в overview_ui.py, поэтому PNG-инфографика в report_export.py (она
# рисует тем же matplotlib, не Altair) использовала свои, чуть другие оттенки
# ("#22c55e" вместо "#2ca02c" и т.д.) — на дашборде и в выгруженном отчёте
# один и тот же смысл выглядел двумя разными цветами.
SENTIMENT_COLOR_DOMAIN = ["Позитив", "Нейтрал", "Негатив"]
SENTIMENT_COLOR_RANGE = ["#2ca02c", "#9e9e9e", "#d62728"]

# Плавная линия без выбросов: monotone проходит ровно через точки данных (в
# отличие от basis/cardinal, которые могут «срезать» экстремумы) — линия
# выглядит менее ломаной, но не искажает значения.
LINE_INTERPOLATE = "monotone"

# Ось с категориями периодов/дат: длинные подписи («24.04.2026–30.04.2026»)
# не помещаются горизонтально в узких панелях. Наклон переводит нужное место
# из горизонтали в диагональ, greedy-overlap — подстраховка на случай, если
# периодов окажется действительно много.
PERIOD_AXIS = alt.Axis(
    labelAngle=-40,
    labelAlign="right",
    labelBaseline="middle",
    labelLimit=160,
    labelOverlap="greedy",
)


def fixed_color_scale(domain: list[str]) -> alt.Scale:
    """Шкала цвета с закреплённым порядком: домен передаёт вызывающий код
    целиком (все возможные категории, не только те, что видны сейчас) —
    тогда цвет метрики не «плывёт» при переключении её видимости."""
    return alt.Scale(domain=domain, range=CATEGORICAL_PALETTE[: len(domain)])
