# -*- coding: utf-8 -*-
"""Ранжирование ролей доступа: none < viewer < editor < owner.

Идентификаторы ролей остаются английскими и не переименовываются. Они лежат в
сохранённых настройках проектов, в сессиях и в записях присутствия — смена
строки сломала бы уже выданные доступы ради вывески. Человеку показывается
подпись из ROLE_TITLES, и менять названия ролей нужно только там.
"""

from __future__ import annotations

ROLE_TITLES = {
    "none": "Без доступа",
    # «Пользователь» вместо прежнего «Просмотр»: роль не только смотрит, она
    # сама выбирает периоды и даты и скачивает готовый отчёт.
    "viewer": "Пользователь",
    # «Аналитик» вместо «Редактора»: правка описаний — часть работы, а не вся
    # роль. Он же настраивает проект и заводит новые.
    "editor": "Аналитик",
    "owner": "Владелец платформы",
}


def role_rank(role: str) -> int:
    return {"none": 0, "viewer": 1, "editor": 2, "owner": 3}.get(role, 0)


def role_title(role: str) -> str:
    """Человеческое название роли. Незнакомую роль показываем как есть."""
    key = str(role or "").strip().lower()
    return ROLE_TITLES.get(key, str(role or ""))
