# -*- coding: utf-8 -*-
"""Ранжирование ролей доступа: none < viewer < editor < owner.

Идентификаторы ролей остаются английскими и не переименовываются. Они лежат в
сохранённых настройках проектов, в сессиях и в записях присутствия — смена
строки сломала бы уже выданные доступы ради вывески. Человеку показывается
подпись из ROLE_TITLES, и менять названия ролей нужно только там.
"""

from __future__ import annotations

ROLE_TITLES = {
    "none": "Без доступа",
    # «Пользователь» вместо прежнего «Просмотр»: роль не только смотрит, она
    # сама выбирает периоды и даты и скачивает готовый отчёт.
    "viewer": "Пользователь",
    # «Аналитик» вместо «Редактора»: правка описаний — часть работы, а не вся
    # роль. Он же настраивает проект и заводит новые.
    "editor": "Аналитик",
    "owner": "Владелец платформы",
}


def role_rank(role: str) -> int:
    return {"none": 0, "viewer": 1, "editor": 2, "owner": 3}.get(role, 0)


def role_title(role: str) -> str:
    """Человеческое название роли. Незнакомую роль показываем как есть."""
    key = str(role or "").strip().lower()
    return ROLE_TITLES.get(key, str(role or ""))


def can_change_project_data(role: str, *, read_only: bool) -> bool:
    """Можно ли загружать файлы, править историю периодов и автозагрузку.

    Нужны роль аналитика или владельца и проект не в режиме «только чтение»
    (демо для всех, кроме владельца платформы). Страницы проверяют это сами,
    а не полагаются на то, что их пункта нет в меню: любая правка навигации
    иначе молча становилась бы дырой в правах.
    """
    return role_rank(role) >= role_rank("editor") and not read_only


def can_see_error_details(role: str, *, is_admin: bool, read_only: bool) -> bool:
    """Показывать ли трейсбек упавшего раздела.

    Подробности нужны тем, кто может с ними что-то сделать: владельцу и
    аналитику проекта. Заказчику показывается только сообщение, и демо-гостю
    тоже — даже если он вошёл кодом аналитика: это посторонний человек, а в
    трейсбеке пути, запросы и куски данных.
    """
    return is_admin or (role_rank(role) >= role_rank("editor") and not read_only)
